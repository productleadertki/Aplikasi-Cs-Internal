const assert=require("node:assert/strict");
const rules=require("../engine.js");
const settings={timezone:"Asia/Jakarta",officeHours:Object.fromEntries([0,1,2,3,4,5,6].map(day=>[day,{enabled:day>0&&day<6,in:"08:00",out:"17:00"}])),holidays:[],routingMethod:"least-active",maxOngoingChats:5,frtMinutes:15,resolutionMinutes:30,pausePendingSla:true};
const late="2026-11-18T22:00:00+07:00";
assert.equal(rules.businessState(late,settings).open,false);
const night=[{id:"night",created:late,status:"Belum ditugaskan",agent:null}];
assert.equal(rules.routeQueue(night,[{name:"A",role:"Agent",online:true}],settings,new Date(late)).length,0);
assert.equal(rules.metrics(night[0],settings,new Date("2026-11-18T23:00:00+07:00")).paused,true);
assert.equal(rules.businessMs(late,"2026-11-19T08:00:00+07:00",settings),0);
assert.equal(rules.businessMs(late,"2026-11-19T08:15:00+07:00",settings),15*60000);
settings.holidays=[{start:"2026-11-19",end:"2026-11-20",description:"Libur"}];
assert.equal(rules.businessState("2026-11-19T09:00:00+07:00",settings).reason,"holiday");
settings.holidays=[];
const queue=Array.from({length:20},(_,i)=>({id:String(i),created:new Date(Date.parse("2026-11-18T08:00:00+07:00")+i*1000).toISOString(),status:"Belum ditugaskan",agent:null}));
const assigned=rules.routeQueue(queue,[{name:"A",role:"Agent",online:true}],settings,new Date("2026-11-18T09:00:00+07:00"));
assert.deepEqual(assigned.map(item=>item.ticket.id),["0","1","2","3","4"]);
assert.equal(queue.filter(item=>item.status==="Belum ditugaskan").length,15);
const resolved={created:"2026-11-18T09:00:00+07:00",firstAgentResponseAt:"2026-11-18T09:05:00+07:00",resolvedAt:"2026-11-18T09:20:00+07:00",status:"Selesai"};
assert.equal(rules.metrics(resolved,settings,new Date("2026-11-18T12:00:00+07:00")).resolutionMs,20*60000);
assert.equal(rules.metrics(resolved,settings).stopped,true);
const surveys=[...Array.from({length:50},()=>({type:"csat",status:"answered",score:4})),...Array.from({length:20},()=>({type:"csat",status:"answered",score:2})),...Array.from({length:30},()=>({type:"csat",status:"expired"}))];
assert.deepEqual(rules.surveyScores(surveys),{sent:100,answered:70,responseRate:70,csat:71.43,csatLow:28.57,ces:null,nps:null});
assert.equal(rules.surveyScores([{type:"ces",status:"answered",score:7},{type:"ces",status:"answered",score:1},{type:"nps",status:"answered",score:10},{type:"nps",status:"answered",score:0}]).ces,4);
console.log("AC-01 through AC-04 passed");
